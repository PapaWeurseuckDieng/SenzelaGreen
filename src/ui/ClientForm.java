    private void ajouter_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ajouter_btnActionPerformed
        // TODO add your handling code here:
        try {
            if(!validerFields()) {
                return;
            }
            
            String nom = nomClient_tf.getText().trim();
            String prenom = prenomClient_tf.getText().trim();
            String adresse = adresseClient_tf.getText().trim();
            String telephone = telephoneClient_tf.getText().trim();
            
            Client client = new Client(nom, prenom, adresse, telephone);
            
            boolean success = ClientDao.addClient(client);
            
            if(success) {
                JOptionPane.showMessageDialog(this, "Ajout réussi");
                resetInput();
                affichageClient();
            } else {
                JOptionPane.showMessageDialog(this, "Erreur lors de l'ajout");
            }
        } catch (SQLException | ClassNotFoundException ex) {
            Logger.getLogger(ClientForm.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_ajouter_btnActionPerformed

    private void modifier_btn1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modifier_btn1ActionPerformed
        // TODO add your handling code here:
        
        try {
            if(!validerFields()) {
                return;
            }
            
            if(c == null) {
                JOptionPane.showMessageDialog(this, "Aucun client sélectionné");
                return;
            }
            
            Client client = new Client(
                c.getIdClient(),
                nomClient_tf.getText().trim(),
                prenomClient_tf.getText().trim(),
                adresseClient_tf.getText().trim(),
                telephoneClient_tf.getText().trim()
            );
            
            boolean success = ClientDao.updateClient(client);
            
            if(success) {
                JOptionPane.showMessageDialog(this, "Modification réussie");
                resetInput();
                affichageClient();
            } else {
                JOptionPane.showMessageDialog(this, "Erreur lors de la modification");
            }
        } catch (SQLException | ClassNotFoundException ex) {
            Logger.getLogger(ClientForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_modifier_btn1ActionPerformed

