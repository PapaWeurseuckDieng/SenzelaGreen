        private boolean validerFields() {
        String nom = nomClient_tf.getText().trim();
        String prenom = prenomClient_tf.getText().trim();
        String adresse = adresseClient_tf.getText().trim();
        String telephone = telephoneClient_tf.getText().trim();
        
        if(nom.isEmpty() || prenom.isEmpty() || adresse.isEmpty() || telephone.isEmpty()) {
            showMessageError("Veuillez remplir tous les champs");
            return false;
        }
        
        // Validation du numéro de téléphone
        if(!telephone.matches("^[0-9]{9}$")) {
            showMessageError("Le téléphone doit contenir 9 chiffres");
            return false;
        }
        
        return true;
    }
    
    private void showMessageError(String message) {
        JOptionPane.showMessageDialog(this, message, "Erreur", JOptionPane.ERROR_MESSAGE);
    }
    
     private void resetInput() {
        nomClient_tf.setText("");
        prenomClient_tf.setText("");
        adresseClient_tf.setText("");
        telephoneClient_tf.setText("");
        c = null;
    }
     
    private void getFormulaire() {
        tableauClient.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                int selectedRow = tableauClient.getSelectedRow();
                if (selectedRow != -1) {
                    try {
                        List<Client> mylist = ClientDao.getAllClients();
                        c = mylist.get(selectedRow);
                        if (c != null) {
                            nomClient_tf.setText(c.getNomClient());
                            prenomClient_tf.setText(c.getPrenomClient());
                            adresseClient_tf.setText(c.getAdresse());
                            telephoneClient_tf.setText(c.getTelephone());
                        }
                    } catch (SQLException | ClassNotFoundException ex) {
                        Logger.getLogger(ClientForm.class.getName()).log(Level.SEVERE, null, ex);
                    }
                }
            }
        });
    }
    
    private void affichageClient() {
        try {
            List<Client> allClients = clientDao.getAllClients();
            UtilsFonction.displayDataInTable(allClients, tableauClient, List.of("idClient"));
        } catch(SQLException | ClassNotFoundException ex) {
            Logger.getLogger(ClientForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    
